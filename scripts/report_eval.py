"""
report_eval.py

Purpose and context:
- Aggregates and reports evaluation CSV results produced by scripts/eval_math500.py.
- Supports single-file summaries (overall accuracy, by subject, by level) and
  pairwise head-to-head comparison across two CSVs (delta counts and examples).

Key functions:
- read_eval_csv: load a CSV of results into a list of dicts with typed fields.
- summarize: compute overall, by-subject, and by-level metrics for a dataset.
- compare: compute head-to-head differences between two datasets keyed by unique_id.
- main: CLI for running summaries and optional comparison, exporting JSON/Markdown.

Integration points:
- Input CSVs are generated by scripts/eval_math500.py.
- Outputs print to stdout and can also be saved to JSON/Markdown for dashboards.
"""

from __future__ import annotations  # future annotations

import argparse  # CLI parsing
import csv  # CSV processing
import json  # JSON export
from collections import defaultdict  # default dicts for aggregation
from dataclasses import dataclass, asdict  # structured results
from pathlib import Path  # filesystem paths
from typing import Dict, List, Optional, Tuple  # typing


@dataclass
class Summary:  # container for summary metrics
    n: int  # number of samples
    correct: int  # number correct
    acc: float  # accuracy
    by_subject: Dict[str, Dict[str, float]]  # per-subject n/correct/acc
    by_level: Dict[str, Dict[str, float]]  # per-level n/correct/acc


def read_eval_csv(path: Path) -> List[Dict]:  # load CSV rows
    rows: List[Dict] = []  # init list
    if not path.exists():  # validate existence
        raise FileNotFoundError(f"CSV not found: {path}")  # error
    with path.open("r", encoding="utf-8") as f:  # open file
        reader = csv.DictReader(f)  # build reader
        for row in reader:  # iterate rows
            try:  # robust typing
                row["score"] = int(row.get("score", 0))  # normalize score
            except Exception:
                row["score"] = 0  # fallback to 0
            rows.append(row)  # append row
    return rows  # return rows


def _breakdown(rows: List[Dict], key: str) -> Dict[str, Dict[str, float]]:  # aggregate helper
    d: Dict[str, List[int]] = defaultdict(lambda: [0, 0])  # n, correct
    for r in rows:  # iterate
        k = r.get(key, "")  # key value
        d[k][0] += 1  # increment n
        d[k][1] += int(r.get("score", 0))  # increment correct
    out: Dict[str, Dict[str, float]] = {}  # init out dict
    for k, (n, c) in d.items():  # compute acc per key
        out[k] = {"n": n, "correct": c, "acc": (c / n if n else 0.0)}  # pack metrics
    return out  # return mapping


def summarize(rows: List[Dict]) -> Summary:  # compute summary metrics
    n = len(rows)  # count samples
    correct = sum(int(r.get("score", 0)) for r in rows)  # sum scores
    acc = (correct / n) if n else 0.0  # accuracy
    by_subject = _breakdown(rows, "subject")  # subject breakdown
    by_level = _breakdown(rows, "level")  # level breakdown
    return Summary(n=n, correct=correct, acc=acc, by_subject=by_subject, by_level=by_level)  # return dataclass


def compare(  # head-to-head compare
    a_rows: List[Dict],  # dataset A
    b_rows: List[Dict],  # dataset B
    top_examples: int = 5,  # number of examples to collect per direction
) -> Dict:
    a = {r["unique_id"]: r for r in a_rows if r.get("unique_id")}  # index A by unique_id
    b = {r["unique_id"]: r for r in b_rows if r.get("unique_id")}  # index B by unique_id
    keys = sorted(set(a.keys()) & set(b.keys()))  # intersection of keys
    improve = regress = tie = 0  # counters
    by_level = defaultdict(lambda: {"improve": 0, "regress": 0, "tie": 0, "n": 0})  # per-level deltas
    by_subject = defaultdict(lambda: {"improve": 0, "regress": 0, "tie": 0, "n": 0})  # per-subject deltas
    examples_improve: List[Dict] = []  # example cases where B>A
    examples_regress: List[Dict] = []  # example cases where B<A
    for k in keys:  # iterate samples
        ra, rb = a[k], b[k]  # rows from A and B
        da = int(rb.get("score", 0)) - int(ra.get("score", 0))  # delta
        lvl = ra.get("level", "")  # level label
        sub = ra.get("subject", "")  # subject label
        by_level[lvl]["n"] += 1  # count by level
        by_subject[sub]["n"] += 1  # count by subject
        if da > 0:  # improvement
            improve += 1  # increment
            by_level[lvl]["improve"] += 1  # level improve
            by_subject[sub]["improve"] += 1  # subject improve
            if len(examples_improve) < top_examples:  # capture example
                examples_improve.append(
                    {
                        "unique_id": k,
                        "subject": sub,
                        "level": lvl,
                        "gt": ra.get("gt", ""),
                        "score_a": int(ra.get("score", 0)),
                        "score_b": int(rb.get("score", 0)),
                    }
                )
        elif da < 0:  # regression
            regress += 1  # increment
            by_level[lvl]["regress"] += 1  # level regress
            by_subject[sub]["regress"] += 1  # subject regress
            if len(examples_regress) < top_examples:  # capture example
                examples_regress.append(
                    {
                        "unique_id": k,
                        "subject": sub,
                        "level": lvl,
                        "gt": ra.get("gt", ""),
                        "score_a": int(ra.get("score", 0)),
                        "score_b": int(rb.get("score", 0)),
                    }
                )
        else:  # tie
            tie += 1  # increment
            by_level[lvl]["tie"] += 1  # level tie
            by_subject[sub]["tie"] += 1  # subject tie
    return {
        "delta_counts": {"improve": improve, "regress": regress, "tie": tie},  # totals
        "by_level": by_level,  # per-level deltas
        "by_subject": by_subject,  # per-subject deltas
        "examples": {"improve": examples_improve, "regress": examples_regress},  # examples
        "n_overlap": len(keys),  # number of overlapping samples
    }


def _print_summary(label: str, s: Summary) -> None:  # human-readable printing
    print(f"== {label} ==")  # title
    print({"n": s.n, "correct": s.correct, "acc": s.acc})  # overall
    print("-- by subject --")  # header
    for k in sorted(s.by_subject.keys()):  # iterate subjects
        d = s.by_subject[k]  # metrics
        print(f"{k}: {d['correct']}/{d['n']} = {d['acc']:.3f}")  # line
    print("-- by level --")  # header
    for k in sorted(s.by_level.keys(), key=lambda x: int(x)):
        d = s.by_level[k]
        print(f"L{k}: {d['correct']}/{d['n']} = {d['acc']:.3f}")


def _print_compare(label_a: str, label_b: str, cmp_res: Dict) -> None:  # print comparison
    print(f"== compare: {label_b} - {label_a} ==")  # header
    print({"overlap": cmp_res["n_overlap"], **cmp_res["delta_counts"]})  # top-level deltas
    print("-- delta by subject --")  # header
    for k in sorted(cmp_res["by_subject"].keys()):  # iterate subjects
        d = cmp_res["by_subject"][k]
        print(f"{k}: +{d['improve']} / -{d['regress']} / ={d['tie']} (n={d['n']})")
    print("-- delta by level --")  # header
    for k in sorted(cmp_res["by_level"].keys(), key=lambda x: int(x)):
        d = cmp_res["by_level"][k]
        print(f"L{k}: +{d['improve']} / -{d['regress']} / ={d['tie']} (n={d['n']})")
    print("-- examples (improve) --")  # examples
    for ex in cmp_res["examples"]["improve"]:
        print(ex)
    print("-- examples (regress) --")  # examples
    for ex in cmp_res["examples"]["regress"]:
        print(ex)


def _save(path: Optional[str], obj: Dict) -> None:  # save helper
    if not path:  # nothing to do
        return
    p = Path(path)  # to Path
    p.parent.mkdir(parents=True, exist_ok=True)  # ensure dir
    if p.suffix.lower() == ".json":  # JSON export
        p.write_text(json.dumps(obj, ensure_ascii=False, indent=2))  # write JSON
    elif p.suffix.lower() in {".md", ".markdown"}:  # Markdown export (simple)
        # simple markdown serialization
        lines = ["# Evaluation Report", "", "```", json.dumps(obj, ensure_ascii=False, indent=2), "```", ""]
        p.write_text("\n".join(lines))  # write MD wrapper
    else:
        # fallback to JSON
        p.with_suffix(p.suffix + ".json").write_text(json.dumps(obj, ensure_ascii=False, indent=2))


def main() -> None:  # CLI entry
    ap = argparse.ArgumentParser(description="Summarize and compare evaluation CSVs")  # parser
    ap.add_argument("--csv", nargs="*", default=[], help="One or more CSVs to summarize")  # inputs
    ap.add_argument("--compare", nargs=2, metavar=("A", "B"), help="Two CSVs to compare head-to-head")  # compare
    ap.add_argument("--out_json", default=None, help="Optional path to write JSON summary")  # json export
    ap.add_argument("--out_md", default=None, help="Optional path to write Markdown summary")  # md export
    ap.add_argument("--top_examples", type=int, default=5, help="How many examples to include in compare")  # k
    args = ap.parse_args()  # parse args

    report: Dict = {"summaries": {}, "comparison": None}  # aggregate result

    # Per-file summaries
    for i, c in enumerate(args.csv):  # iterate CSVs
        label = Path(c).stem  # label from filename
        rows = read_eval_csv(Path(c))  # load
        summ = summarize(rows)  # summarize
        report["summaries"][label] = asdict(summ)  # add
        _print_summary(label, summ)  # print human-readable

    # Pairwise comparison
    if args.compare:  # if comparison requested
        a, b = args.compare  # unpack
        label_a, label_b = Path(a).stem, Path(b).stem  # labels
        rows_a = read_eval_csv(Path(a))  # load A
        rows_b = read_eval_csv(Path(b))  # load B
        cmp_res = compare(rows_a, rows_b, top_examples=args.top_examples)  # compare
        report["comparison"] = {"a": label_a, "b": label_b, **cmp_res}  # attach
        _print_compare(label_a, label_b, cmp_res)  # print

    # Optional save
    if args.out_json or args.out_md:  # export
        _save(args.out_json, report)  # JSON
        _save(args.out_md, report)  # Markdown


if __name__ == "__main__":  # entrypoint
    main()  # run CLI

